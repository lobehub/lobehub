def generate(target: Path) -> None:
    spec = yaml.safe_load(SPEC_PATH.read_text(encoding="utf8"))
    registry = TypeRegistry(spec)
    registry.emit_components()
    operations = collect_operations(spec, registry)

    target.mkdir(parents=True, exist_ok=True)
    (target / "types.py").write_text(render_types(registry), encoding="utf8")
    sync_source, _ = render_resources(operations, asynchronous=False, type_names=registry.taken)
    async_source, _ = render_resources(operations, asynchronous=True, type_names=registry.taken)
    (target / "resources.py").write_text(sync_source, encoding="utf8")
    (target / "async_resources.py").write_text(async_source, encoding="utf8")
    (target / "__init__.py").write_text(
        HEADER + '"""Code generated from the OpenAPI spec; see `lobehub.types` for the public schemas."""\n',
        encoding="utf8",
    )
    format_python(target)


def format_python(target: Path) -> None:
    """Normalize with the pinned ruff so output only depends on the spec."""
    ruff = [sys.executable, "-m", "ruff"]
    config = ["--config", str(PKG_ROOT / "pyproject.toml")]
    subprocess.run(
        [*ruff, "check", "--fix", "--quiet", "--select", "F401,I", *config, str(target)], check=False
    )
    subprocess.run([*ruff, "format", "--quiet", *config, str(target)], check=True)


def snapshot(directory: Path) -> Dict[str, str]:
    return {
        str(path.relative_to(directory)): path.read_text(encoding="utf8")
        for path in sorted(directory.rglob("*.py"))
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the committed output is out of date")
    args = parser.parse_args()

    if not args.check:
        if OUTPUT_DIR.exists():
            shutil.rmtree(OUTPUT_DIR)
        generate(OUTPUT_DIR)
        print(f"Generated {OUTPUT_DIR.relative_to(PKG_ROOT)} from {SPEC_PATH.name}")
        return 0

    # Inside the package tree so ruff resolves the same config and first-party imports.
    fresh = Path(tempfile.mkdtemp(dir=OUTPUT_DIR.parent, prefix=".generated-check-"))
    try:
        generate(fresh)
        expected = snapshot(fresh)
        actual = snapshot(OUTPUT_DIR) if OUTPUT_DIR.exists() else {}
    finally:
        shutil.rmtree(fresh)
    if expected == actual:
        print("src/lobehub/generated is up to date with openapi.yml")
        return 0

    print("src/lobehub/generated is out of date with packages/openapi/openapi.yml.", file=sys.stderr)
    print(
        "Run `uv run python scripts/generate.py` in packages/sdk-python and commit the result.\n",
        file=sys.stderr,
    )
    for name in sorted(set(expected) | set(actual)):
        if expected.get(name) != actual.get(name):
            diff = difflib.unified_diff(
                actual.get(name, "").splitlines(),
                expected.get(name, "").splitlines(),
                f"committed/{name}",
                f"generated/{name}",
                lineterm="",
                n=1,
            )
            print("\n".join(list(diff)[:40]), file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
