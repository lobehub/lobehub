HEADER = """# This file is generated by scripts/generate.py from packages/openapi/openapi.yml.
# Do not edit it by hand: change the spec and run `uv run python scripts/generate.py`.
"""

# Names the generated modules import; a schema with one of these names is renamed.
RESERVED_TYPE_NAMES = {
    "Any",
    "Dict",
    "FileTypes",
    "List",
    "Literal",
    "NotRequired",
    "Optional",
    "TypedDict",
    "Union",
}

# Page metadata fields: the remaining array property of a page holds its items.
PAGE_FIELDS = {"hasMore", "nextCursor", "total", "totalSize"}

ENVELOPE_FIELDS = {"data", "success", "timestamp"}


# ---------------------------------------------------------------- naming


def words(name: str) -> List[str]:
    """Split camelCase / kebab-case / snake_case / dotted names into words."""
    spaced = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", name)
    spaced = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", spaced)
    return [w for w in re.split(r"[^A-Za-z0-9]+", spaced) if w]


def pascal(name: str) -> str:
    result = "".join(w[:1].upper() + w[1:] for w in words(name))
    if not result:
        return "Value"
    return result if result[0].isalpha() else f"T{result}"


def snake(name: str) -> str:
    result = "_".join(w.lower() for w in words(name)) or "value"
    if result[0].isdigit():
        result = f"_{result}"
    return f"{result}_" if keyword.iskeyword(result) else result


def docstring(text: str, indent: str) -> str:
    """A safely escaped triple-quoted docstring, or '' for no text."""
    text = (text or "").strip()
    if not text:
        return ""
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines = text.splitlines()
    if len(lines) == 1 and len(text) < 70 and not text.endswith('"'):
        return f'{indent}"""{text}"""\n'
    body = "\n".join(f"{indent}{line}".rstrip() for line in lines)
    return f'{indent}"""\n{body}\n{indent}"""\n'


# ---------------------------------------------------------------- types


def literal(value: Any) -> str:
    """A Python literal for a JSON `const` / `enum` value."""
    if isinstance(value, bool):
        return "True" if value else "False"
    return json.dumps(value)


# References to named types are wrapped in REF markers while an expression is
# built, then rendered quoted (runtime-evaluated aliases) or bare (lazy
# annotations under `from __future__ import annotations`).
REF = "\x00"


def render(expr: str, quoted: bool) -> str:
    return re.sub(f"{REF}(\\w+){REF}", (lambda m: f'"{m.group(1)}"') if quoted else r"\1", expr)


def union(members: List[str]) -> str:
    unique: List[str] = []
    nullable = False
    for member in members:
        if member == "None":
            nullable = True
        elif member == "Any":
            return "Any"
        elif member not in unique:
            unique.append(member)
    if not unique:
        return "None"
    expr = unique[0] if len(unique) == 1 else f"Union[{', '.join(unique)}]"
    return f"Optional[{expr}]" if nullable else expr


@dataclass
class TypedDictDef:
    name: str
    description: str
    # (wire key, type expression, required)
    fields: List[Tuple[str, str, bool]]


@dataclass
class AliasDef:
    name: str
    description: str
    expr: str


class TypeRegistry:
    def __init__(self, spec: Dict[str, Any]):
        self.spec = spec
        self.schemas: Dict[str, Any] = spec["components"]["schemas"]
        self.component_names = {name: self._component_name(name) for name in self.schemas}
        self.taken = set(self.component_names.values())
        self.defs: List[Any] = []

    @staticmethod
    def _component_name(name: str) -> str:
        result = pascal(name) if not name.isidentifier() else name
        return f"{result}Model" if result in RESERVED_TYPE_NAMES else result

    def unique(self, hint: str) -> str:
        name = pascal(hint)
        if name in RESERVED_TYPE_NAMES:
            name += "Model"
        candidate, index = name, 2
        while candidate in self.taken:
            candidate, index = f"{name}{index}", index + 1
        self.taken.add(candidate)
        return candidate

    def resolve(self, schema: Dict[str, Any]) -> Dict[str, Any]:
        while "$ref" in schema:
            schema = self.schemas[schema["$ref"].rsplit("/", 1)[-1]]
        return schema

    def emit_components(self) -> None:
        for raw_name, schema in self.schemas.items():
            name = self.component_names[raw_name]
            self.define(schema, name, named=name)

    def define(self, schema: Dict[str, Any], hint: str, named: Optional[str] = None) -> str:
        """Type expression for `schema`; objects become TypedDicts named after `hint`."""
        if "$ref" in schema:
            return f"{REF}{self.component_names[schema['$ref'].rsplit('/', 1)[-1]]}{REF}"

        expr = self._expr(schema, hint, named)
        if named and not expr.startswith(f"{REF}{named}{REF}"):
            # A named component that is not an object: emit an alias.
            self.defs.append(AliasDef(named, schema.get("description", ""), expr))
            return f"{REF}{named}{REF}"
        return expr

    def _expr(self, schema: Dict[str, Any], hint: str, named: Optional[str]) -> str:
        if "const" in schema:
            return f"Literal[{literal(schema['const'])}]" if schema["const"] is not None else "None"
        if "enum" in schema:
            literals = [literal(v) for v in schema["enum"] if v is not None]
            members = [f"Literal[{', '.join(literals)}]"] if literals else []
            if None in schema["enum"]:
                members.append("None")
            return union(members)

        for combinator in ("anyOf", "oneOf"):
            if combinator in schema:
                variants = schema[combinator]
                members = [
                    self.define(variant, self._variant_hint(hint, variant, index, len(variants)))
                    for index, variant in enumerate(variants)
                ]
                return union(members)

        types = schema.get("type")
        if isinstance(types, list):
            members = [self._expr({**schema, "type": t}, hint, named) for t in types]
            return union(members)

        if types == "null":
            return "None"
        if types == "boolean":
            return "bool"
        if types == "integer":
            return "int"
        if types == "number":
            return "float"
        if types == "string":
            return "FileTypes" if schema.get("format") == "binary" else "str"
        if types == "array":
            items = schema.get("items") or {}
            return f"List[{self.define(items, f'{hint}Item')}]"
        if types == "object" or "properties" in schema:
            return self._object(schema, hint, named)
        return "Any"

    def _variant_hint(self, hint: str, variant: Dict[str, Any], index: int, total: int) -> str:
        variant = self.resolve(variant) if "$ref" not in variant else variant
        for key in ("type", "role", "kind", "status", "object"):
            prop = (variant.get("properties") or {}).get(key) or {}
            if isinstance(prop.get("const"), str):
                return f"{hint}{pascal(prop['const'])}"
        return hint if total == 1 else f"{hint}Variant{index + 1}"

    def _object(self, schema: Dict[str, Any], hint: str, named: Optional[str]) -> str:
        properties: Dict[str, Any] = schema.get("properties") or {}
        if not properties:
            extra = schema.get("additionalProperties")
            value = self.define(extra, f"{hint}Value") if isinstance(extra, dict) and extra else "Any"
            return f"Dict[str, {value}]"

        name = named or self.unique(hint)
        required = set(schema.get("required") or [])
        definition = TypedDictDef(name, schema.get("description", ""), [])
        self.defs.append(definition)
        for key, prop in properties.items():
            definition.fields.append((key, self.define(prop, f"{name}{pascal(key)}"), key in required))
        return f"{REF}{name}{REF}"


def render_types(registry: TypeRegistry) -> str:
    out = [
        HEADER,
        '"""Request and response schemas of the LobeHub REST API, as `TypedDict`s."""\n\n',
        "from __future__ import annotations\n\n",
        "from typing import Any, Dict, List, Optional, Union\n\n",
        "from typing_extensions import Literal, NotRequired, TypedDict\n\n",
        "from .._uploads import FileTypes\n\n",
    ]
    names: List[str] = []
    for definition in registry.defs:
        names.append(definition.name)
        out.append("\n")
        if isinstance(definition, AliasDef):
            out.append(f"{definition.name} = {render(definition.expr, quoted=True)}\n")
            if definition.description:
                out.append(docstring(definition.description, ""))
            continue

        identifiers = all(k.isidentifier() and not keyword.iskeyword(k) for k, _, _ in definition.fields)
        if identifiers:
            out.append(f"class {definition.name}(TypedDict):\n")
            out.append(docstring(definition.description, "    "))
            for key, expr, required in definition.fields:
                annotation = render(expr, quoted=False)
                out.append(f"    {key}: {annotation if required else f'NotRequired[{annotation}]'}\n")
        else:
            # Keys like `from` or `x-foo` need the functional syntax (evaluated eagerly).
            out.append(f'{definition.name} = TypedDict(\n    "{definition.name}",\n    {{\n')
            for key, expr, required in definition.fields:
                annotation = render(expr, quoted=True)
                annotation = annotation if required else f"NotRequired[{annotation}]"
                out.append(f"        {json.dumps(key)}: {annotation},\n")
            out.append("    },\n)\n")
            if definition.description:
                out.append(docstring(definition.description, ""))

    out.append("\n__all__ = [\n")
    out.extend(f'    "{name}",\n' for name in sorted(names))
    out.append("]\n")
    return "".join(out)


# ---------------------------------------------------------------- operations


@dataclass
class Param:
    wire: str
    py: str
    location: str  # path | query | header
    expr: str
    required: bool
    description: str
    deprecated: bool = False


@dataclass
class Operation:
    resource: str
    method: str
    http_method: str
    path: str
    summary: str
    description: str
    scopes: Optional[List[str]]
    deprecated: bool
    params: List[Param] = field(default_factory=list)
    body_expr: Optional[str] = None
    body_required: bool = False
    body_kind: Optional[str] = None  # json | multipart
    response_kind: str = "json"  # json | envelope | binary | empty
    response_expr: str = "Any"
    # (item array key, item type expression) for cursor-paginated lists
    page: Optional[Tuple[str, str]] = None


HEADER_PARAM_NAMES = {"X-Workspace-Id": "workspace_id", "Idempotency-Key": "idempotency_key"}


def collect_operations(spec: Dict[str, Any], registry: TypeRegistry) -> List[Operation]:
    operations: List[Operation] = []
    for path, item in spec["paths"].items():
        for http_method, raw in item.items():
            resource, method = raw["operationId"].split(".")
            op_name = pascal(raw["operationId"])
            op = Operation(
                resource=resource,
                method=method,
                http_method=http_method.upper(),
                path=path,
                summary=raw.get("summary", ""),
                description=raw.get("description", ""),
                scopes=raw.get("x-required-scopes"),
                deprecated=bool(raw.get("deprecated")),
            )

            parameters = [registry_parameter(spec, p) for p in raw.get("parameters", [])]
            path_order = re.findall(r"{(\w+)}", path)
            parameters.sort(
                key=lambda p: path_order.index(p["name"]) if p["in"] == "path" else len(path_order)
            )
            for p in parameters:
                py_name = HEADER_PARAM_NAMES.get(p["name"]) if p["in"] == "header" else None
                expr = registry.define(p.get("schema") or {}, f"{op_name}{pascal(p['name'])}")
                op.params.append(
                    Param(
                        wire=p["name"],
                        py=py_name or snake(p["name"]),
                        location=p["in"],
                        expr=expr,
                        required=bool(p.get("required")) or p["in"] == "path",
                        description=p.get("description", ""),
                        deprecated=bool(p.get("deprecated")),
                    )
                )

            body = raw.get("requestBody")
            if body:
                content = body["content"]
                kind = "json" if "application/json" in content else "multipart"
                schema = content["application/json" if kind == "json" else "multipart/form-data"]["schema"]
                op.body_kind = kind
                op.body_required = bool(body.get("required"))
                op.body_expr = registry.define(schema, f"{op_name}Body")

            classify_response(op, raw, registry, op_name)
            operations.append(op)
    return operations


def registry_parameter(spec: Dict[str, Any], param: Dict[str, Any]) -> Dict[str, Any]:
    if "$ref" in param:
        return spec["components"]["parameters"][param["$ref"].rsplit("/", 1)[-1]]
    return param


def classify_response(op: Operation, raw: Dict[str, Any], registry: TypeRegistry, op_name: str) -> None:
    success = [(code, r) for code, r in raw["responses"].items() if str(code).startswith("2")]
    if not success:
        op.response_kind = "empty"
        op.response_expr = "None"
        return
    _, response = success[0]
    content = response.get("content") or {}
    if "application/json" not in content:
        if content:
            op.response_kind = "binary"
            op.response_expr = "BinaryResponse"
        else:
            op.response_kind = "empty"
            op.response_expr = "None"
        return

    schema = content["application/json"]["schema"]
    resolved = registry.resolve(schema)
    props = resolved.get("properties") or {}
    if ENVELOPE_FIELDS <= set(props) and (props["success"].get("const") is True):
        op.response_kind = "envelope"
        data_schema = props["data"]
        op.response_expr = registry.define(data_schema, f"{op_name}Response")
        op.page = page_shape(registry, data_schema, f"{op_name}Response")
    else:
        op.response_kind = "json"
        op.response_expr = registry.define(schema, f"{op_name}Response")


def page_shape(registry: TypeRegistry, schema: Dict[str, Any], hint: str) -> Optional[Tuple[str, str]]:
    """`(items key, item type)` when `schema` is a cursor page."""
    candidates = [schema]
    resolved = registry.resolve(schema)
    candidates += resolved.get("anyOf") or resolved.get("oneOf") or []
    for candidate in candidates:
        page = registry.resolve(candidate)
        props = page.get("properties") or {}
        if not {"hasMore", "nextCursor"} <= set(props):
            continue
        arrays = [
            k for k, v in props.items() if k not in PAGE_FIELDS and registry.resolve(v).get("type") == "array"
        ]
        key = "items" if "items" in arrays else (arrays[0] if len(arrays) == 1 else None)
        if key is None:
            return None
        items = registry.resolve(props[key]).get("items") or {}
        page_name = (
            pascal(hint)
            if "$ref" not in candidate
            else registry.component_names[candidate["$ref"].rsplit("/", 1)[-1]]
        )
        return key, registry.define(items, f"{page_name}{pascal(key)}Item")
    return None


# ---------------------------------------------------------------- resources


COMMON_KWARGS = """        extra_headers: Optional[Mapping[str, str]] = None,
        extra_query: Optional[Mapping[str, object]] = None,
        extra_body: Optional[Mapping[str, object]] = None,
        timeout: Optional[float] = None,
        max_retries: Optional[int] = None,
"""


def method_doc(op: Operation) -> str:
    parts = [op.summary or f"{op.http_method} {op.path}"]
    if op.description:
        parts.append(op.description)
    if op.deprecated:
        parts.append("Deprecated.")
    parts.append(f"`{op.http_method} {op.path}`")
    return "\n\n".join(parts)


def signature(op: Operation, *, for_pages: bool = False) -> Tuple[str, List[Param]]:
    """The parameter list (after `self`) and the params it binds."""
    lines: List[str] = []
    path_params = [p for p in op.params if p.location == "path"]
    # A page iterator owns `cursor`, and deprecated params (`format=array`) would break paging.
    other = [
        p
        for p in op.params
        if p.location != "path" and not (for_pages and (p.wire == "cursor" or p.deprecated))
    ]
    for p in path_params:
        lines.append(f"        {p.py}: {render(p.expr, quoted=False)},\n")
    body_required = op.body_expr is not None and op.body_required
    if body_required:
        lines.append(f"        body: {render(op.body_expr, quoted=False)},\n")
    lines.append("        *,\n")
    if op.body_expr is not None and not body_required:
        lines.append(f"        body: Optional[{render(op.body_expr, quoted=False)}] = None,\n")
    for p in sorted(other, key=lambda p: not p.required):
        expr = render(p.expr, quoted=False)
        if p.required:
            lines.append(f"        {p.py}: {expr},\n")
        else:
            lines.append(
                f"        {p.py}: {expr if expr.startswith('Optional[') else f'Optional[{expr}]'} = None,\n"
            )
    lines.append(COMMON_KWARGS)
    return "".join(lines), path_params + other


def path_expr(op: Operation) -> str:
    params = {p.wire: p.py for p in op.params if p.location == "path"}
    if not params:
        return json.dumps(op.path)
    return "f" + json.dumps(re.sub(r"{(\w+)}", lambda m: f"{{_path({params[m.group(1)]})}}", op.path))


def mapping(params: List[Param], location: str, *, cursor_var: Optional[str] = None) -> str:
    selected = [p for p in params if p.location == location]
    if not selected and not (cursor_var and location == "query"):
        return "None"
    entries = [f"{json.dumps(p.wire)}: {p.py}" for p in selected]
    if cursor_var and location == "query":
        entries.append(f'"cursor": {cursor_var}')
    return "{" + ", ".join(entries) + "}"


def render_method(op: Operation, asynchronous: bool) -> str:
    out: List[str] = []
    name = snake(op.method)
    params_sig, bound = signature(op)
    ret = render(op.response_expr, quoted=False)
    prefix = "async def" if asynchronous else "def"
    out.append(f"    {prefix} {name}(\n        self,\n{params_sig}    ) -> {ret}:\n")
    out.append(docstring(method_doc(op), "        "))
    call = "await self._client._request" if asynchronous else "self._client._request"
    args = [
        json.dumps(op.http_method),
        path_expr(op),
        f"query={mapping(bound, 'query')}",
        f"headers={mapping(bound, 'header')}",
    ]
    if op.body_kind == "json":
        args.append("json=body")
    elif op.body_kind == "multipart":
        args.append("multipart=body")
    args += [
        f"response={json.dumps(op.response_kind)}",
        "extra_headers=extra_headers",
        "extra_query=extra_query",
        "extra_body=extra_body",
        "timeout=timeout",
        "max_retries=max_retries",
    ]
    joined = ",\n            ".join(args)
    if op.response_kind == "empty":
        out.append(f"        {call}(\n            {joined},\n        )\n")
    else:
        out.append(
            f"        return cast(\n            {json.dumps(ret)},\n            {call}(\n            {joined},\n            ),\n        )\n"
        )

    if op.page:
        key, item_expr = op.page
        item = render(item_expr, quoted=False)
        page_sig, page_bound = signature(op, for_pages=True)
        iterator = "AsyncIterator" if asynchronous else "Iterator"
        has_cursor = any(p.wire == "cursor" for p in op.params)
        if not has_cursor:
            return "".join(out)
        page_sig = page_sig.replace("        *,\n", "        *,\n        cursor: Optional[str] = None,\n", 1)
        out.append(f"\n    def iter_{name}(\n        self,\n{page_sig}    ) -> {iterator}[{item}]:\n")
        out.append(
            docstring(
                f"Iterate every item of `{name}` across pages, starting at `cursor`.\n\n"
                f"Each page is fetched with `{name}()` and its `nextCursor` is passed back until `hasMore` is false.",
                "        ",
            )
        )
        forwarded = [f"{p.py}={p.py}" for p in page_bound if p.location != "path"]
        positional = [p.py for p in page_bound if p.location == "path"]
        if op.body_expr is not None:
            forwarded.append("body=body")
        forwarded += [
            "extra_headers=extra_headers",
            "extra_query=extra_query",
            "extra_body=extra_body",
            "timeout=timeout",
            "max_retries=max_retries",
        ]
        call_args = ", ".join([*positional, *forwarded, "cursor=page_cursor"])
        fetch = "async def" if asynchronous else "def"
        awaited = "await " if asynchronous else ""
        out.append(
            f"        {fetch} fetch(page_cursor: Optional[str]) -> Any:\n"
            f"            return {awaited}self.{name}({call_args})\n\n"
            f"        return {'aiter_pages' if asynchronous else 'iter_pages'}(fetch, {json.dumps(key)}, cursor)\n"
        )
    return "".join(out)


def render_resources(
    operations: List[Operation], asynchronous: bool, type_names: Set[str]
) -> Tuple[str, List[Tuple[str, str]]]:
    by_resource: Dict[str, List[Operation]] = {}
    for op in operations:
        by_resource.setdefault(op.resource, []).append(op)

    base = "AsyncAPIResource" if asynchronous else "SyncAPIResource"
    prefix = "Async" if asynchronous else ""
    used_types = set()
    for op in operations:
        for expr in [
            op.response_expr,
            op.body_expr or "",
            *(p.expr for p in op.params),
            (op.page or ("", ""))[1],
        ]:
            used_types.update(re.findall(f"{REF}(\\w+){REF}", expr))

    out = [
        HEADER,
        f'"""{"Async" if asynchronous else "Sync"} resource classes: one per operationId prefix of the spec."""\n\n',
        "from __future__ import annotations\n\n",
        "from typing import TYPE_CHECKING, Any, "
        + ("AsyncIterator, " if asynchronous else "Iterator, ")
        + "Dict, List, Mapping, Optional, Union, cast\n\n",
        "from typing_extensions import Literal\n\n",
        f"from .._pagination import {'aiter_pages' if asynchronous else 'iter_pages'}\n",
        f"from .._resource import {base}, _path\n",
        "from .._response import BinaryResponse\n",
        "from .._uploads import FileTypes\n\n",
        "if TYPE_CHECKING:\n",
        "    from .types import (\n",
        *(f"        {name},\n" for name in sorted(used_types)),
        "    )\n",
    ]
    resources: List[Tuple[str, str]] = []
    for resource, ops in by_resource.items():
        # `usage` is both a resource and a schema: the class gives way.
        stem = pascal(resource)
        class_name = f"{prefix}{stem}Resource" if stem in type_names else f"{prefix}{stem}"
        resources.append((snake(resource), class_name))
        out.append(f"\n\nclass {class_name}({base}):\n")
        out.append(docstring(f"`client.{snake(resource)}`: the `{resource}.*` operations.", "    "))
        for index, op in enumerate(ops):
            if index:
                out.append("\n")
            out.append(render_method(op, asynchronous))

    accessor = f"{prefix}GeneratedResources"
    out.append(f"\n\nclass {accessor}:\n")
    out.append(docstring("Every generated resource as a lazily created attribute of the client.", "    "))
    out.append("    _client: Any\n")
    for attr, class_name in resources:
        out.append(f"\n    @cached_property\n    def {attr}(self) -> {class_name}:\n")
        out.append(f"        return {class_name}(self._client)\n")
    out.append("\n\n__all__ = [\n")
    out.extend(f'    "{name}",\n' for name in sorted([accessor, *(c for _, c in resources)]))
    out.append("]\n")

    source = "".join(out).replace(
        "from typing_extensions import Literal\n",
        "from typing_extensions import Literal\n\nfrom .._compat import cached_property\n",
        1,
    )
    return source, resources


