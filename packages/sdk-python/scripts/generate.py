"""Generate ``src/lobehub/generated/`` from the committed OpenAPI spec.

The spec (``packages/openapi/openapi.yml``) is the single source of truth: it
yields the ``TypedDict`` schemas (``generated/types.py``) and one resource class
per operationId prefix, in a sync (``generated/resources.py``) and an async
(``generated/async_resources.py``) flavor. ``agents.list`` becomes
``client.agents.list()``, the same name the TypeScript SDK uses.

The output is committed so installing the SDK never runs generation, and
``--check`` keeps it from drifting when routes change (the same contract as
``packages/sdk/scripts/generate-sdk.ts --check``).

Usage (from ``packages/sdk-python``):
    uv run python scripts/generate.py          # regenerate src/lobehub/generated
    uv run python scripts/generate.py --check  # exit 1 when it is out of date
"""

