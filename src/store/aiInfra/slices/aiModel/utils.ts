import { getAutoGeneratedModelSourceId } from 'model-bank/standardParameters';

interface ModelWithId {
  id: string;
}

interface DeduplicateRemoteModelsResult<T> {
  duplicateIds: string[];
  models: T[];
  removedCount: number;
}

/**
 * Enabled builtin ids that a fetched catalog did not return.
 * An empty catalog is not treated as authoritative, so a blank response does not
 * turn every builtin off. Models the catalog did return are left untouched.
 */
export const enabledBuiltinIdsMissingFromCatalog = (
  builtinIds: readonly string[],
  catalogIds: ReadonlySet<string>,
  currentModels: readonly { enabled?: boolean; id: string }[],
): string[] => {
  if (catalogIds.size === 0) return [];

  const enabledIds = new Set(
    currentModels.filter((model) => model.enabled).map((model) => model.id),
  );

  return builtinIds.filter((id) => enabledIds.has(id) && !catalogIds.has(id));
};

export const deduplicateRemoteModels = <T extends ModelWithId>(
  models: T[],
): DeduplicateRemoteModelsResult<T> => {
  const duplicateIds: string[] = [];
  const duplicateIdSet = new Set<string>();
  const sourceModelIds = new Set(models.map(({ id }) => id));
  const modelMap = new Map<string, T>();

  for (const model of models) {
    if (!modelMap.has(model.id)) {
      modelMap.set(model.id, model);
      continue;
    }

    if (!duplicateIdSet.has(model.id)) {
      duplicateIds.push(model.id);
      duplicateIdSet.add(model.id);
    }

    const sourceModelId = getAutoGeneratedModelSourceId(model.id);
    const shouldKeepLast = !!sourceModelId && sourceModelIds.has(sourceModelId);

    if (shouldKeepLast) {
      modelMap.delete(model.id);
      modelMap.set(model.id, model);
    }
  }

  return {
    duplicateIds,
    models: [...modelMap.values()],
    removedCount: models.length - modelMap.size,
  };
};
